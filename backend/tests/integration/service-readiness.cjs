  await t.test('QR choice combos enforce serving times and retain choices through staff acceptance',async()=>{
    const floor=await one("INSERT INTO floors(restaurant_id,name) VALUES($1,'Readiness dining') RETURNING id",[rid]);
    const qrToken=randomUUID().replaceAll('-','');
    await one("INSERT INTO dining_tables(restaurant_id,floor_id,table_no,qr_token) VALUES($1,$2,'QR-READY',$3) RETURNING id",[rid,floor.id,qrToken]);
    await pool.query('INSERT INTO table_request_settings(restaurant_id,ordering_enabled) VALUES($1,true) ON CONFLICT(restaurant_id) DO UPDATE SET ordering_enabled=true',[rid]);
    const dish=await newDish('QR choice meal'),drink=await newDish('QR choice drink',20);
    const config=await request('PUT',`/menu/products/${dish.id}/service-options`,{groups:[{name:'Drink',choose:1,options:[{productId:drink.id,quantity:1,extraPrice:10}]}]});
    const choices=[{groupId:config.groups[0].id,productId:drink.id}];
    const url=`/public/tables/${qrToken}`;
    const payload=()=>({clientKey:randomUUID(),items:[{productId:dish.id,quantity:1,comboSelections:choices}]});
    await request('PATCH','/availability',{productId:drink.id,soldOut:true});
    const menu=await request('GET',`${url}/menu`,undefined,200,null);
    assert.equal(menu.categories.flatMap(c=>c.dishes).find(d=>d.id===dish.id).soldOut,true);
    await request('POST',`${url}/orders`,payload(),400,null);
    await request('PATCH','/availability',{productId:drink.id,soldOut:false});
    const today=Number((await one("SELECT EXTRACT(DOW FROM NOW() AT TIME ZONE 'Asia/Kolkata') AS day")).day);
    await request('PUT',`/menu/products/${drink.id}/service-options`,{schedule:[{days:[(today+2)%7],opensAt:'07:00',closesAt:'11:00'}]});
    await request('POST',`${url}/orders`,payload(),400,null);
    await request('PUT',`/menu/products/${drink.id}/service-options`,{schedule:[]});
    const submitted=await request('POST',`${url}/orders`,payload(),201,null);
    const acceptance=await request('POST',`/table-requests/${submitted.id}/accept`,{});
    const accepted={order:await request('GET',`/orders/${acceptance.order.id}`)};
    assert.equal(accepted.order.items[0].comboParts[0].productId,drink.id);
    assert.equal(accepted.order.totalAmount,110);
    const second=await request('POST',`${url}/orders`,payload(),201,null);
    const addition=await request('POST',`/table-requests/${second.id}/accept`,{});
    const appended={order:await request('GET',`/orders/${addition.order.id}`)};
    assert.equal(appended.order.id,accepted.order.id);
    assert.equal(appended.order.totalAmount,220);
    assert.equal(appended.order.items[1].comboParts[0].productId,drink.id);
    await finish(appended.order);
  });
